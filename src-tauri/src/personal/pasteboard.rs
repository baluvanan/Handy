//! Full-fidelity clipboard snapshot/restore guarded by a per-paste session
//! marker.
//!
//! Pasting goes through the clipboard, so every paste temporarily replaces
//! whatever the user had copied. This module makes that round trip lossless
//! and safe:
//!
//! 1. **Snapshot everything.** Every pasteboard item and every type on it
//!    (RTF, HTML, images, file URLs, app-private types) is captured as raw
//!    bytes, and written back byte-for-byte, not just plain text or one image.
//! 2. **Session marker.** Our transcript is published together with a custom
//!    type holding a unique session id. Before restoring, we check that the
//!    clipboard still carries *this* session's id (and that the change count
//!    has not moved). If anything else was copied in the meantime, the user's
//!    newer copy wins and nothing is restored.
//! 3. **Transient.** The transcript is also tagged
//!    `org.nspasteboard.TransientType` (plus the related concealment markers)
//!    so clipboard managers that honour <http://nspasteboard.org> ignore it.
//!
//! The logic is written against the small [`Pasteboard`] trait so it can be
//! unit-tested without macOS; `pasteboard_macos.rs` implements it with
//! `NSPasteboard`.

#![cfg_attr(not(target_os = "macos"), allow(dead_code))]

use std::sync::atomic::{AtomicU64, Ordering};

/// Custom pasteboard type carrying the id of the paste session that wrote the
/// clipboard. Reverse-DNS under the app identifier so it never collides.
pub const SESSION_MARKER_TYPE: &str = "com.baluvanan.handy-personal.paste-session";

/// UTI for plain UTF-8 text (`NSPasteboardTypeString`).
pub const PLAIN_TEXT_TYPE: &str = "public.utf8-plain-text";

/// nspasteboard.org markers: clipboard managers skip transient/concealed/
/// auto-generated content, so our short-lived transcript never lands in the
/// user's clipboard history.
pub const TRANSIENT_TYPES: [&str; 3] = [
    "org.nspasteboard.TransientType",
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.AutoGeneratedType",
];

/// One representation (type + raw bytes) of a pasteboard item.
pub type Representation = (String, Vec<u8>);

/// One pasteboard item with every representation it offered.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct ItemSnapshot {
    pub representations: Vec<Representation>,
}

impl ItemSnapshot {
    pub fn get(&self, data_type: &str) -> Option<&[u8]> {
        self.representations
            .iter()
            .find(|(t, _)| t == data_type)
            .map(|(_, d)| d.as_slice())
    }
}

/// Everything on the clipboard at one moment.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct Snapshot {
    pub items: Vec<ItemSnapshot>,
}

// Test-only helpers: the real pasteboard reads the marker directly
// (`Pasteboard::session_marker`), so these would be dead code on macOS.
#[cfg(test)]
impl Snapshot {
    pub fn is_empty(&self) -> bool {
        self.items.iter().all(|i| i.representations.is_empty())
    }

    /// The session id stored on any item, if the clipboard holds one of our
    /// transcripts.
    pub fn session_marker(&self) -> Option<String> {
        self.items
            .iter()
            .find_map(|i| i.get(SESSION_MARKER_TYPE))
            .map(|bytes| String::from_utf8_lossy(bytes).into_owned())
    }
}

/// The minimal clipboard surface the session logic needs.
pub trait Pasteboard {
    /// Monotonic counter bumped whenever the clipboard contents are replaced.
    fn change_count(&self) -> i64;
    /// Every item and representation currently on the clipboard.
    fn snapshot(&self) -> Snapshot;
    /// Replace the clipboard with exactly `items` (empty clears it). Returns
    /// the change count after the write.
    fn write_items(&self, items: &[ItemSnapshot]) -> i64;
    /// The session marker currently on the clipboard, without copying every
    /// other representation.
    fn session_marker(&self) -> Option<String>;
}

/// A process-unique id for one paste. Not a UUID crate dependency: pid +
/// wall clock nanos + a counter is unique enough for "is this still ours".
pub fn new_session_id() -> String {
    static COUNTER: AtomicU64 = AtomicU64::new(0);
    let nanos = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_nanos())
        .unwrap_or(0);
    format!(
        "{}-{}-{}",
        std::process::id(),
        nanos,
        COUNTER.fetch_add(1, Ordering::Relaxed)
    )
}

/// The item we publish for a transcript: plain text, the session marker and
/// the transient markers (empty payloads).
pub fn transcript_item(text: &str, session_id: &str) -> ItemSnapshot {
    let mut representations: Vec<Representation> = vec![
        (PLAIN_TEXT_TYPE.to_string(), text.as_bytes().to_vec()),
        (
            SESSION_MARKER_TYPE.to_string(),
            session_id.as_bytes().to_vec(),
        ),
    ];
    for t in TRANSIENT_TYPES {
        representations.push((t.to_string(), Vec::new()));
    }
    ItemSnapshot { representations }
}

/// Plain text only — what we leave behind when the user asked for the
/// transcript to stay on the clipboard (so clipboard managers *do* record it).
pub fn plain_text_item(text: &str) -> ItemSnapshot {
    ItemSnapshot {
        representations: vec![(PLAIN_TEXT_TYPE.to_string(), text.as_bytes().to_vec())],
    }
}

/// Why a restore did or did not happen.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum RestoreDecision {
    /// The clipboard still holds this session's transcript: restore.
    Restore,
    /// The change count moved: something else wrote the clipboard.
    ChangedExternally,
    /// The change count matches but the marker is not ours (or missing).
    /// Should not happen in practice; treated as "not ours" to be safe.
    MarkerMismatch,
}

/// Pure guard: restore only if nothing else touched the clipboard since our
/// write *and* it still carries this session's marker.
pub fn decide_restore(
    expected_change_count: i64,
    current_change_count: i64,
    current_marker: Option<&str>,
    session_id: &str,
) -> RestoreDecision {
    if current_change_count != expected_change_count {
        return RestoreDecision::ChangedExternally;
    }
    match current_marker {
        Some(marker) if marker == session_id => RestoreDecision::Restore,
        _ => RestoreDecision::MarkerMismatch,
    }
}

/// What to leave on the clipboard once the paste is done.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum AfterPaste {
    /// Put the user's previous clipboard back.
    RestorePrevious,
    /// Leave the transcript as plain text (`ClipboardHandling::CopyToClipboard`).
    KeepTranscript(String),
}

/// One paste's clipboard transaction: snapshot, marked write, guarded restore.
#[derive(Debug)]
pub struct PasteSession {
    pub id: String,
    pub saved: Snapshot,
    pub change_count: i64,
}

impl PasteSession {
    /// Snapshots the clipboard and publishes `text` with this session's
    /// marker. The caller then sends the paste keystroke.
    pub fn begin<P: Pasteboard>(pasteboard: &P, text: &str) -> Self {
        let saved = pasteboard.snapshot();
        let id = new_session_id();
        let change_count = pasteboard.write_items(&[transcript_item(text, &id)]);
        Self {
            id,
            saved,
            change_count,
        }
    }

    /// For writers that publish the transcript themselves (the lazy-promise
    /// path): adopt an already-taken snapshot and the post-write change count.
    pub fn adopt(id: String, saved: Snapshot, change_count: i64) -> Self {
        Self {
            id,
            saved,
            change_count,
        }
    }

    /// The guard decision against the clipboard as it is now.
    pub fn check<P: Pasteboard>(&self, pasteboard: &P) -> RestoreDecision {
        decide_restore(
            self.change_count,
            pasteboard.change_count(),
            pasteboard.session_marker().as_deref(),
            &self.id,
        )
    }

    /// Settles the session. Only touches the clipboard when it still holds
    /// this session's transcript; returns the decision for logging.
    pub fn finish<P: Pasteboard>(self, pasteboard: &P, after: AfterPaste) -> RestoreDecision {
        let decision = self.check(pasteboard);
        if decision == RestoreDecision::Restore {
            match after {
                AfterPaste::RestorePrevious => {
                    pasteboard.write_items(&self.saved.items);
                }
                AfterPaste::KeepTranscript(text) => {
                    pasteboard.write_items(&[plain_text_item(&text)]);
                }
            }
        }
        decision
    }
}

#[cfg(test)]
pub(crate) mod fake {
    use super::*;
    use std::cell::{Cell, RefCell};

    /// In-memory pasteboard with NSPasteboard's change-count semantics.
    #[derive(Default)]
    pub struct FakePasteboard {
        pub items: RefCell<Vec<ItemSnapshot>>,
        pub count: Cell<i64>,
    }

    impl FakePasteboard {
        pub fn with(items: Vec<ItemSnapshot>) -> Self {
            Self {
                items: RefCell::new(items),
                count: Cell::new(1),
            }
        }

        /// Simulates the user (or another app) copying something.
        pub fn user_copies(&self, items: Vec<ItemSnapshot>) {
            *self.items.borrow_mut() = items;
            self.count.set(self.count.get() + 1);
        }
    }

    impl Pasteboard for FakePasteboard {
        fn change_count(&self) -> i64 {
            self.count.get()
        }
        fn snapshot(&self) -> Snapshot {
            Snapshot {
                items: self.items.borrow().clone(),
            }
        }
        fn write_items(&self, items: &[ItemSnapshot]) -> i64 {
            *self.items.borrow_mut() = items.to_vec();
            self.count.set(self.count.get() + 1);
            self.count.get()
        }
        fn session_marker(&self) -> Option<String> {
            self.snapshot().session_marker()
        }
    }
}

#[cfg(test)]
mod tests {
    use super::fake::FakePasteboard;
    use super::*;

    fn item(reps: &[(&str, &[u8])]) -> ItemSnapshot {
        ItemSnapshot {
            representations: reps
                .iter()
                .map(|(t, d)| (t.to_string(), d.to_vec()))
                .collect(),
        }
    }

    /// A rich-text copy (RTF + HTML + plain) and a second image item, as e.g.
    /// copying from Pages or a browser selection with an image produces.
    fn rich_clipboard() -> Vec<ItemSnapshot> {
        vec![
            item(&[
                ("public.rtf", b"{\\rtf1 \\b bold\\b0 }"),
                ("public.html", b"<b>bold</b>"),
                (PLAIN_TEXT_TYPE, b"bold"),
                ("com.example.private", &[0, 159, 146, 150]),
            ]),
            item(&[
                ("public.png", &[0x89, b'P', b'N', b'G', 0, 1, 2]),
                ("public.tiff", &[b'I', b'I', 42, 0]),
            ]),
        ]
    }

    #[test]
    fn begin_snapshots_every_item_and_type() {
        let pb = FakePasteboard::with(rich_clipboard());
        let session = PasteSession::begin(&pb, "hello");
        assert_eq!(session.saved.items, rich_clipboard());
        assert_eq!(session.saved.items[0].representations.len(), 4);
        assert_eq!(session.saved.items[1].representations.len(), 2);
    }

    #[test]
    fn begin_publishes_marked_transient_transcript() {
        let pb = FakePasteboard::with(rich_clipboard());
        let session = PasteSession::begin(&pb, "hello");
        let now = pb.snapshot();
        assert_eq!(now.items.len(), 1);
        assert_eq!(now.items[0].get(PLAIN_TEXT_TYPE), Some(&b"hello"[..]));
        assert_eq!(now.session_marker().as_deref(), Some(session.id.as_str()));
        assert!(now.items[0].get("org.nspasteboard.TransientType").is_some());
        assert_eq!(session.change_count, pb.change_count());
    }

    #[test]
    fn finish_restores_all_items_byte_for_byte() {
        let pb = FakePasteboard::with(rich_clipboard());
        let session = PasteSession::begin(&pb, "hello");
        assert_eq!(
            session.finish(&pb, AfterPaste::RestorePrevious),
            RestoreDecision::Restore
        );
        assert_eq!(pb.snapshot().items, rich_clipboard());
        assert!(pb.session_marker().is_none());
    }

    #[test]
    fn a_copy_made_during_the_paste_is_never_overwritten() {
        let pb = FakePasteboard::with(rich_clipboard());
        let session = PasteSession::begin(&pb, "hello");
        let newer = vec![item(&[(PLAIN_TEXT_TYPE, b"copied meanwhile")])];
        pb.user_copies(newer.clone());
        assert_eq!(
            session.finish(&pb, AfterPaste::RestorePrevious),
            RestoreDecision::ChangedExternally
        );
        assert_eq!(pb.snapshot().items, newer);
    }

    #[test]
    fn another_sessions_marker_is_not_restored_over() {
        let pb = FakePasteboard::with(rich_clipboard());
        let first = PasteSession::begin(&pb, "first");
        // A second paste session took over the clipboard.
        let second = PasteSession::begin(&pb, "second");
        assert_eq!(
            first.finish(&pb, AfterPaste::RestorePrevious),
            RestoreDecision::ChangedExternally
        );
        assert_eq!(
            pb.snapshot().items[0].get(PLAIN_TEXT_TYPE),
            Some(&b"second"[..])
        );
        // The second session restores what *it* saw (the first transcript).
        assert_eq!(
            second.finish(&pb, AfterPaste::RestorePrevious),
            RestoreDecision::Restore
        );
    }

    #[test]
    fn marker_mismatch_with_same_change_count_does_not_restore() {
        // Same change count, but the marker on the clipboard is foreign (e.g.
        // a writer that does not bump the counter). Guard on the marker too.
        let pb = FakePasteboard::with(rich_clipboard());
        let session = PasteSession::begin(&pb, "hello");
        let mut items = pb.items.borrow().clone();
        items[0].representations[1].1 = b"someone-else".to_vec();
        *pb.items.borrow_mut() = items.clone();
        assert_eq!(
            session.finish(&pb, AfterPaste::RestorePrevious),
            RestoreDecision::MarkerMismatch
        );
        assert_eq!(pb.snapshot().items, items);
    }

    #[test]
    fn empty_clipboard_is_cleared_again() {
        let pb = FakePasteboard::with(Vec::new());
        let session = PasteSession::begin(&pb, "hello");
        assert!(session.saved.is_empty());
        session.finish(&pb, AfterPaste::RestorePrevious);
        assert!(pb.snapshot().is_empty());
    }

    #[test]
    fn keep_transcript_leaves_plain_unmarked_text() {
        let pb = FakePasteboard::with(rich_clipboard());
        let session = PasteSession::begin(&pb, "hello");
        session.finish(&pb, AfterPaste::KeepTranscript("hello".into()));
        let now = pb.snapshot();
        assert_eq!(now.items, vec![plain_text_item("hello")]);
        assert!(now.session_marker().is_none());
    }

    #[test]
    fn keep_transcript_respects_the_guard() {
        let pb = FakePasteboard::with(rich_clipboard());
        let session = PasteSession::begin(&pb, "hello");
        pb.user_copies(vec![item(&[(PLAIN_TEXT_TYPE, b"mine")])]);
        session.finish(&pb, AfterPaste::KeepTranscript("hello".into()));
        assert_eq!(
            pb.snapshot().items[0].get(PLAIN_TEXT_TYPE),
            Some(&b"mine"[..])
        );
    }

    #[test]
    fn decide_restore_matrix() {
        assert_eq!(
            decide_restore(5, 5, Some("a"), "a"),
            RestoreDecision::Restore
        );
        assert_eq!(
            decide_restore(5, 6, Some("a"), "a"),
            RestoreDecision::ChangedExternally
        );
        assert_eq!(
            decide_restore(5, 5, Some("b"), "a"),
            RestoreDecision::MarkerMismatch
        );
        assert_eq!(
            decide_restore(5, 5, None, "a"),
            RestoreDecision::MarkerMismatch
        );
    }

    #[test]
    fn session_ids_are_unique() {
        let a = new_session_id();
        let b = new_session_id();
        assert_ne!(a, b);
    }
}
